/**
 * 一件事，加上我怎麼想。
 *
 * 工作、輸出、反思、日記、程式共用同一張表：欄位完全一樣，分開只會逼你
 * 在記錄前先做一個沒有後果的分類，那是純摩擦力。要分開看就用「類型」篩。
 *
 * 這裡刻意不存事件本身（軌跡、時數、commit）。那些留在原本的系統裡，
 * 需要時用「連結」指過去——這張表只放經過思考的東西。
 */
export interface Writing {
  id: string;
  /** 記下這一則的時間（ISO）。date 只到日，同一天的先後只有它分得出來 */
  createdAt: string;
  /** 只有一個日期：這件事發生／我想到它的那天 */
  date: string | null;
  title: string;
  /** 週計劃／顯化／思緒——這件事屬於我生活的哪一塊，跟關鍵字是不同層次的分類 */
  topic: string;
  /** 紀事只用關鍵字分類，不再另外分領域——一件事想到什麼就記什麼，先分類反而卡住 */
  keywords: string;
  /** 主體。其他欄位都是為了讓這一欄好找 */
  note: string;
  /**
   * 這則放在哪裡。網址（HackMD、部落格、PR）或純文字都可以——
   * 「紙本日記 8/17」「Obsidian／求職筆記」也算，不是每件事都在線上。
   */
  link: string;
  /** 讀了什麼之後寫的：書名或文章標題，人看得懂的那一份 */
  sourceTitle: string;
  /** 出處本身的類型（書籍／文章），跟這則書寫自己的 kind 是兩件事——
   * 不要拿這欄去湊「類型」顯示，那正是之前把兩者混在一起的錯誤做法 */
  sourceKind: string;
  /** 這則自己的類型。專欄堆底下不只「書寫」一種，範本庫還有論述、每日計畫 */
  kindId: string;
  kindName: string;
  kindSlug: string;
  /** 同一件事給程式看的那一份；空白代表不是從系統裡的紀錄延伸來的 */
  sourceId: string;
  /** 「是」代表私人：鎖上的時候伺服器不會把這一列送到瀏覽器 */
  private: string;
  /** 封面圖，選填——像部落格文章那種示意圖，不跟出處的書籍封面連動 */
  coverUrl: string;
}
